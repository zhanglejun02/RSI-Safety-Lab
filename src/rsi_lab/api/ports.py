"""Public extension ports. Trusted plugins are installed explicitly, never from config code."""
from pathlib import Path
from typing import Protocol
from .contracts import (SystemDescriptor, SystemSnapshot, PublicTask, CandidateDraft,
                        ActivationCommand, ActivationReceipt, ExecutionReceipt)


class ToolSession(Protocol):
    """Only request-scoped public tools, no oracle/state-store/commit handles."""
    def descriptions(self) -> tuple[dict, ...]: ...
    def call(self, name: str, arguments: dict, operation_id: str) -> dict: ...


class PublicEvaluator(Protocol):
    """Fresh isolated public tasks only. Scalar feedback belongs to the subject."""
    def evaluate(self, candidate: SystemSnapshot, operation_id: str) -> dict: ...


class SystemAdapter(Protocol):
    def describe(self) -> SystemDescriptor: ...
    def snapshot(self) -> SystemSnapshot: ...
    def fork(self, snapshot: SystemSnapshot, directory: Path) -> "SystemAdapter": ...
    def propose(self, operation_id: str, evaluator: PublicEvaluator) -> CandidateDraft: ...
    def run_task(self, task: PublicTask, tools: ToolSession, operation_id: str) -> ExecutionReceipt: ...
    def activate(self, command: ActivationCommand) -> ActivationReceipt: ...
    def activation_status(self, operation_id: str) -> ActivationReceipt | None: ...


class TaskPlan(Protocol):
    seed: int
    rounds: tuple  # Opaque, canonically serializable task-owned round records.


class TaskEnvironment(Protocol):
    def snapshot(self): ...
    def prepare(self, round_plan): ...
    def public_tasks(self, round_plan) -> tuple[PublicTask, ...]: ...
    def tools(self, task_id: str, namespace: str) -> ToolSession: ...
    def traces(self, round_plan) -> tuple: ...
    def evaluate(self, round_plan, complete: bool = True): ...
    def synthetic_cost(self, round_plan) -> float: ...


class TaskPackage(Protocol):
    tool_protocol: str
    def plan(self, seed, family, partition, horizon, schedule) -> TaskPlan: ...
    def create_environment(self, directory: Path, snapshot=None) -> TaskEnvironment: ...
    def probe_options(self) -> tuple: ...
    def probe_schedule(self, plan_id: str) -> str: ...


class Detector(Protocol):
    """Receives public AuditView + bounded ProbeAccess, returns report/evidence."""
    def detect(self, view, probes): ...


class AdmissionPolicy(Protocol):
    def decide(self, view, report, evidence=None): ...
